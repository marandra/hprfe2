# Main
#####################################################################

if __name__ == "__main__":

    ARGS = docopt(__doc__, version="v0.9")
    KEYWORD = _process_arguments(ARGS)

    C = Common(root_path=Path(ARGS["--root"]))

    if KEYWORD == "INIT_HELP":
        print(init_func.__doc__)
    elif KEYWORD == "INIT":
        init_func(Path(ARGS["<template>"]), not ARGS["--no-quiet-params"])
    elif KEYWORD == "SAMPLE_HELP":
        print(sample_create.__doc__)
    elif KEYWORD == "SAMPLE_CREATE":
        sample_create()
    elif KEYWORD == "SAMPLE_DEPLOY":
        sample_create()
    elif KEYWORD == "SAMPLE":
        print(3)
    elif KEYWORD == "BASES_HELP":
        print(3)
    elif KEYWORD == "BASES_GENERATE":
        print(3)
    elif KEYWORD == "BASES_PACK":
        print(3)
    elif KEYWORD == "BASES":
        print(3)
    else:
        print("Need a command. Try with --help.")
        exit()
